class Resp(object):
    """One HTTP result. Never raises; failures come back with .error set."""

    def __init__(self, url, status=None, body="", final_url=None,
                 length=None, ctype="", error=None):
        self.url = url
        self.status = status
        self.body = body
        self.final_url = final_url or url
        self.length = length
        self.ctype = ctype
        self.error = error

    @property
    def ok(self):
        return self.error is None and self.status is not None and self.status < 400

    @property
    def redirected(self):
        return self.final_url.rstrip("/") != self.url.rstrip("/")

    @property
    def throttled(self):
        """Rate-limited, so its real status is unknown.

        Kept distinct from broken on purpose: "we could not check this" and
        "this is dead" are different claims and only one of them is work.
        """
        return self.status in THROTTLE_STATUS


def safe_url(url):
    """Make a URL sendable: IDNA for the host, percent-encoding for the rest.

    Real sites link to files with en-dashes and accented characters in the
    filename. urllib refuses those outright, and the resulting UnicodeEncodeError
    reads exactly like a broken link — a false finding, which is worse than a
    missed one. '%' is in the safe set so already-encoded URLs survive untouched.
    """
    try:
        parts = urllib.parse.urlsplit(url)
    except ValueError:
        return url
    host = parts.hostname or ""
    try:
        host = host.encode("idna").decode("ascii")
    except Exception:
        pass
    netloc = "%s:%d" % (host, parts.port) if parts.port else host
    if parts.username:
        cred = parts.username + ((":" + parts.password) if parts.password else "")
        netloc = cred + "@" + netloc
    path = urllib.parse.quote(parts.path, safe="/%:@&=+$,;~!*'()[]")
    query = urllib.parse.quote(parts.query, safe="/%:@&=+$,;?~!*'()[]")
    return urllib.parse.urlunsplit((parts.scheme, netloc, path, query, ""))


def _request(url, method="GET", timeout=TIMEOUT, extra_headers=None):
    headers = dict(UA)
    if extra_headers:
        headers.update(extra_headers)
    LIMITER.wait(url)
    req = urllib.request.Request(safe_url(url), headers=headers, method=method)
    return urllib.request.urlopen(req, timeout=timeout)


def fetch(url, timeout=TIMEOUT, read_body=True):
    """GET a URL, transparently gunzipping. Returns a Resp, never raises."""
    try:
        with _request(url, "GET", timeout) as r:
            raw = r.read() if read_body else b""
            if r.headers.get("Content-Encoding") == "gzip" or url.endswith(".gz"):
                try:
                    raw = gzip.decompress(raw)
                except OSError:
                    pass
            return Resp(
                url,
                status=r.status,
                body=raw.decode("utf-8", "replace") if read_body else "",
                final_url=r.geturl(),
                length=len(raw) if read_body else _int(r.headers.get("Content-Length")),
                ctype=(r.headers.get("Content-Type") or "").split(";")[0].strip().lower(),
            )
    except urllib.error.HTTPError as e:
        # A 404 is a result, not a failure — we are here to find them.
        return Resp(url, status=e.code, final_url=getattr(e, "url", url) or url,
                    ctype=(e.headers.get("Content-Type") or "").split(";")[0].strip().lower()
                    if e.headers else "")
    except Exception as e:
        return Resp(url, error=_short_err(e))


# "Come back later", not "gone". Squarespace and most CDNs throttle a fast
# crawler with these, and reporting a client's working page as a broken link
# because we hammered it is the worst kind of false positive — it sends someone
# to fix a page that was never broken.
#
# This is not hypothetical. An early version at 6 workers with no pacing had
# Squarespace return 429 for /trauma-therapy, a live page linked from 398 others,
# and the report called it a broken link.
RETRY_STATUS = frozenset((408, 425, 429, 500, 502, 503, 504))
THROTTLE_STATUS = frozenset((429, 503))
RETRY_WAIT = 2.0
MAX_RETRIES = 3
CRAWL_DELAY = 0.2       # seconds between requests to one host, ~5/s
MAX_BACKOFF = 30.0


class HostLimiter(object):
    """Spaces requests to a single host, however many threads are running.

    Worker count controls how many hosts we talk to at once; this controls how
    hard we lean on any one of them. Without it, concurrency and politeness are
    the same dial and you cannot raise one without losing the other.
    """

    def __init__(self, delay=CRAWL_DELAY):
        self.delay = delay
        self._next = {}
        self._lock = threading.Lock()

    def wait(self, url):
        if self.delay <= 0:
            return
        host = urllib.parse.urlparse(url).netloc.lower()
        with self._lock:
            now = time.monotonic()
            due = self._next.get(host, 0.0)
            sleep_for = max(0.0, due - now)
            self._next[host] = max(now, due) + self.delay
        if sleep_for:
            time.sleep(min(sleep_for, MAX_BACKOFF))


LIMITER = HostLimiter()


def retry_after(headers, attempt):
    """Honour Retry-After when the server sends one, else exponential backoff."""
    if headers:
        raw = headers.get("Retry-After")
        if raw:
            try:
                return min(float(raw), MAX_BACKOFF)
            except (TypeError, ValueError):
                pass
    return min(RETRY_WAIT * (2 ** attempt), MAX_BACKOFF)


def probe(url, timeout=15, _attempt=0):
    """HEAD a URL for status + size, falling back to a ranged GET.

    Plenty of hosts (and most CDNs fronting images) either reject HEAD outright
    or answer it without Content-Length, so the fallback is not optional.

    Throttling responses are retried once after a pause; see RETRY_STATUS.
    """
    try:
        with _request(url, "HEAD", timeout) as r:
            length = _int(r.headers.get("Content-Length"))
            ctype = (r.headers.get("Content-Type") or "").split(";")[0].strip().lower()
            if length is not None:
                return Resp(url, status=r.status, final_url=r.geturl(),
                            length=length, ctype=ctype)
            head = Resp(url, status=r.status, final_url=r.geturl(), ctype=ctype)
    except urllib.error.HTTPError as e:
        if e.code in (403, 405, 501):      # HEAD refused; try a real GET
            head = None
        elif e.code in RETRY_STATUS and _attempt < MAX_RETRIES:
            # Throttling arrives here, on the HEAD — this is the branch a 429
            # actually takes, so retrying only after the GET fallback never fires.
            time.sleep(retry_after(e.headers, _attempt))
            return probe(url, timeout=timeout, _attempt=_attempt + 1)
        else:
            return Resp(url, status=e.code, final_url=getattr(e, "url", url) or url)
    except Exception as e:
        head = Resp(url, error=_short_err(e))

    got = fetch(url, timeout=timeout, read_body=True)
    result = got if (got.ok or head is None or head.error) else head
    if result.status in RETRY_STATUS and _attempt < MAX_RETRIES:
        time.sleep(retry_after(None, _attempt))
        return probe(url, timeout=timeout, _attempt=_attempt + 1)
    return result


def _int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return None


def _short_err(e):
    msg = str(e) or e.__class__.__name__
    return msg[:120]


class StatusCache(object):
    """Check each distinct URL once, however many pages link to it.

    On a therapy site the header nav is on all 300 pages. Without this the
    scan is 300x slower and hammers the client's server for no new information.
    """

    def __init__(self):
        self._done = {}
        self._locks = {}
        self._guard = threading.Lock()

    def get(self, url, fn):
        with self._guard:
            if url in self._done:
                return self._done[url]
            lock = self._locks.setdefault(url, threading.Lock())
        with lock:
            if url in self._done:
                return self._done[url]
            result = fn(url)
            with self._guard:
                self._done[url] = result
                self._locks.pop(url, None)
            return result

    def __len__(self):
        return len(self._done)


# ---------------------------------------------------------------- sitemap

def find_sitemap(base):
    for name in SITEMAP_CANDIDATES:
        r = fetch("%s/%s" % (base, name))
        if r.ok and ("<loc>" in r.body or "<sitemapindex" in r.body or "<urlset" in r.body):
            return r.url, r.body
    return None, None


def collect_urls(base, verbose=True):
    """Every page URL in the sitemap, following nested sitemap indexes."""
    start, body = find_sitemap(base)
    if not start:
        return [], None

    if verbose:
        print("Sitemap          : %s" % start)

    locs = re.findall(r"<loc>\s*(.*?)\s*</loc>", body)
    pages, children = [], []
    if "<sitemapindex" in body:
        children = locs
    else:
        pages = locs

    for child in children:
        if re.search(r"(image|video|news)[-_]?sitemap|sitemap[-_]?(image|video|news)",
                     child, re.I):
            continue        # media sitemaps list assets, not pages
        r = fetch(child)
        if not r.ok:
            print("  ! could not read %s (%s)" % (child, r.error or r.status))
            continue
        pages += re.findall(r"<loc>\s*(.*?)\s*</loc>", r.body)

    seen, out = set(), []
    for u in pages:
        u = html.unescape(u.strip())
        if u and u not in seen:
            seen.add(u)
            out.append(u)
    return out, start


# ---------------------------------------------------------------- parsing

SKIP_TEXT_IN = {"script", "style", "noscript", "template", "svg"}
# Chrome, footers, and legal boilerplate are not the page's content.
STRIP_CONTAINERS = {"nav", "header", "footer", "aside"}


class PageParser(HTMLParser):
    """Pull the on-page facts out of raw HTML with a real parser.

    Regex is fine for a canonical tag. It is not fine for images and links,
    where attribute order, self-closing forms, and stray quotes all vary.
    """

    def __init__(self):
        HTMLParser.__init__(self, convert_charrefs=True)
        self.title = None
        self.meta_desc = None
        self.meta_robots = ""
        self.canonical = None
        self.lang = None
        self.h1s = []
        self.images = []      # dicts: src, alt, alt_missing, width, height, decorative
        self.links = []       # dicts: href, anchor, rel, nofollow
        self._text = []
        self._skip_depth = 0
        self._chrome_depth = 0
        self._in_title = False
        self._h1_buf = None
        self._a_buf = None
        self._a_attrs = None

    # -- helpers
    @staticmethod
    def _d(attrs):
        return {k.lower(): (v or "") for k, v in attrs}

    def _start(self, tag, attrs):
        a = self._d(attrs)

        if tag in SKIP_TEXT_IN:
            self._skip_depth += 1
            return
        if tag in STRIP_CONTAINERS:
            self._chrome_depth += 1

        if tag == "html" and a.get("lang"):
            self.lang = a["lang"].strip()

        elif tag == "title":
            self._in_title = True

        elif tag == "meta":
            name = (a.get("name") or a.get("property") or "").lower()
            if name == "description" and self.meta_desc is None:
                self.meta_desc = a.get("content", "").strip()
            elif name == "robots":
                self.meta_robots = a.get("content", "").lower()

        elif tag == "link":
            rels = a.get("rel", "").lower().split()
            if "canonical" in rels and not self.canonical:
                self.canonical = a.get("href", "").strip()

        elif tag == "h1":
            self._h1_buf = []

        elif tag == "img":
            src = (a.get("src") or a.get("data-src") or a.get("data-lazy-src") or "").strip()
            if src and not src.startswith("data:"):
                alt = a.get("alt")
                self.images.append({
                    "src": src,
                    "alt": (alt or "").strip(),
                    # alt="" is a deliberate "this is decorative" and is correct.
                    # A missing alt attribute is the actual defect.
                    "alt_missing": alt is None,
                    "alt_empty": alt is not None and not alt.strip(),
                    "width": a.get("width", ""),
                    "height": a.get("height", ""),
                    "decorative": any(h in src.lower() for h in DECORATIVE_HINTS),
                    "lazy": "loading" in a and a.get("loading", "").lower() == "lazy",
                })

        elif tag == "a":
            self._a_attrs = a
            self._a_buf = []

    def handle_starttag(self, tag, attrs):
        self._start(tag.lower(), attrs)

    def handle_startendtag(self, tag, attrs):
        tag = tag.lower()
        if tag in SKIP_TEXT_IN or tag in STRIP_CONTAINERS:
            return          # self-closing, so it opens and shuts nothing
        self._start(tag, attrs)

    def handle_endtag(self, tag):
        tag = tag.lower()
        if tag in SKIP_TEXT_IN:
            self._skip_depth = max(0, self._skip_depth - 1)
        elif tag in STRIP_CONTAINERS:
            self._chrome_depth = max(0, self._chrome_depth - 1)
        elif tag == "title":
            self._in_title = False
        elif tag == "h1" and self._h1_buf is not None:
            h = " ".join("".join(self._h1_buf).split())
            if h:
                self.h1s.append(h)
            self._h1_buf = None
        elif tag == "a" and self._a_attrs is not None:
            href = (self._a_attrs.get("href") or "").strip()
            rel = self._a_attrs.get("rel", "").lower()
            if href:
                self.links.append({
                    "href": href,
                    "anchor": " ".join("".join(self._a_buf or []).split())[:120],
                    "rel": rel,
                    "nofollow": "nofollow" in rel,
                })
            self._a_attrs, self._a_buf = None, None

    def handle_data(self, data):
        if self._in_title:
            self.title = ((self.title or "") + data).strip()
            return
        if self._skip_depth:
            return
        if self._h1_buf is not None:
            self._h1_buf.append(data)
        if self._a_buf is not None:
            self._a_buf.append(data)
        if not self._chrome_depth:
            self._text.append(data)

    @property
    def text(self):
        return " ".join(" ".join(self._text).split())


def parse_page(body):
    p = PageParser()
    try:
        p.feed(body)
        p.close()
    except Exception:
        pass        # a malformed page still yields whatever parsed before the break
    return p


# ---------------------------------------------------------------- duplicates

WORD_RE = re.compile(r"[a-z0-9']+")
SHINGLE_N = 6

# Shingles catch pages that share PHRASES. They score ~0 on two pages that say
# the same thing in different words — which is the more common and more damaging
# case: two pages built for the same topic, competing with each other.
#
# TF-IDF cosine over single terms catches that middle band with no model and no
# API key. It does not do synonymy: "worry" and "anxiety" are unrelated tokens
# here. Real embeddings would catch that, at the cost of an API key and a
# per-crawl charge — see README.
# Calibrated against a 122-page site with five templated location pages. Those
# scored 58-68% against each other; the highest unrelated pair was terms-of-service
# vs privacy-policy at 35%, and two genuinely different service pages scored 34%.
# 0.50 sits in the gap with margin on both sides.
TOPIC_RATIO = 0.50      # cosine above which two pages are "the same topic"
TOPIC_MIN_TERMS = 40    # too few distinct terms and cosine is meaningless

# Small closed-class list. Not a full stopword set — TF-IDF already discounts
# anything common across the corpus. This just removes the words so frequent
# that they distort short pages.
STOPWORDS = frozenset("""
a an and are as at be been but by can do does for from had has have he her his
how i if in into is it its me my no not of on or our out she so than that the
their them then there these they this to too us was we were what when where
which who will with would you your about after all also any because before
being between both during each few more most other over same some such through
under until up very via while
""".split())


def shingles(text):
    """Set of overlapping 6-word phrases. Order-sensitive, cheap, good enough."""
    words = WORD_RE.findall(text.lower())
    if len(words) < SHINGLE_N:
        return set()
    return {
        hash(" ".join(words[i:i + SHINGLE_N]))
        for i in range(len(words) - SHINGLE_N + 1)
    }


def terms_of(text):
    """Bag of meaningful terms for TF-IDF. Counter of word -> frequency."""
    return Counter(w for w in WORD_RE.findall(text.lower())
                   if len(w) > 2 and w not in STOPWORDS)


def tfidf_vectors(pages):
    """L2-normalised TF-IDF vector per page, as {term: weight}.

    Normalising means cosine is a plain dot product, so the pair loop stays
    cheap: iterate the shorter vector and look up the longer one.
    """
    n = len(pages)
    doc_freq = Counter()
    for p in pages:
        doc_freq.update(p["terms"].keys())

    vectors = []
    for p in pages:
        vec = {}
        for term, tf in p["terms"].items():
            df = doc_freq[term]
            # No hard exclusion for terms on every page. An earlier version
            # dropped df == n as "navigation", which meant a corpus made mostly
            # of one template erased its own shared vocabulary and scored 0.0 —
            # the same self-erasure already fixed in the shingle path, and it
            # only failed on the small multi-location sites that need it most.
            # Smoothed IDF already handles it: df == n gives log(2), a real but
            # small weight, which is exactly the intent.
            #
            # Sublinear TF so one word repeated 50 times cannot dominate.
            vec[term] = (1.0 + math.log(tf)) * math.log(1.0 + n / float(df))
        norm = math.sqrt(sum(w * w for w in vec.values()))
        vectors.append({t: w / norm for t, w in vec.items()} if norm else {})
    return vectors


def cosine(a, b):
    if len(a) > len(b):
        a, b = b, a
    return sum(w * b.get(t, 0.0) for t, w in a.items())


def find_topic_overlap(pages, threshold=TOPIC_RATIO, include_blog=False):
    """Pages covering the same topic in different words.

    Returns [(page_a, page_b, score)] sorted by score. These are CANDIDATES to
    review, not proven cannibalisation — two pages can rank for different
    queries and both earn their traffic, and merging them destroys one. Proving
    competition needs a live SERP check this tool does not do.
    """
    live = [p for p in pages if len(p.get("terms") or ()) >= TOPIC_MIN_TERMS]
    if len(live) < 2:
        return []

    vectors = tfidf_vectors(live)
    out = []
    for i, a in enumerate(live):
        for j in range(i + 1, len(live)):
            b = live[j]
            # Two blog posts about anxiety are expected on a content site and
            # would swamp the finding. Pairs involving a non-blog page are the
            # ones worth a look.
            if not include_blog and is_blog(a["url"]) and is_blog(b["url"]):
                continue
            score = cosine(vectors[i], vectors[j])
            if score >= threshold:
                out.append((a, b, score))
    out.sort(key=lambda t: -t[2])
    return out


def topic_clusters(pages, threshold=TOPIC_RATIO, include_blog=False):
    """Group overlapping pages into sets, not pairs.

    Five templated location pages produce ten pairs, which reads as ten problems
    when it is one: a page template reused across five towns. Connected
    components over the pair graph collapse that into a single row naming all
    five. Returns [(sorted_urls, low_score, high_score)].
    """
    pairs = find_topic_overlap(pages, threshold, include_blog)
    if not pairs:
        return []

    adjacent = defaultdict(set)
    scores = {}
    for a, b, s in pairs:
        adjacent[a["url"]].add(b["url"])
        adjacent[b["url"]].add(a["url"])
        scores[frozenset((a["url"], b["url"]))] = s

    clusters, seen = [], set()
    for start in sorted(adjacent):
        if start in seen:
            continue
        # Breadth-first walk of one connected component.
        members, queue = set(), [start]
        while queue:
            node = queue.pop()
            if node in members:
                continue
            members.add(node)
            queue.extend(adjacent[node] - members)
        seen |= members

        inside = [s for pair, s in scores.items() if pair <= members]
        clusters.append((sorted(members), min(inside), max(inside)))

    clusters.sort(key=lambda c: (-len(c[0]), -c[2]))
    return clusters


GOLDEN_ANGLE = 2.399963229728653
MAP_EDGE_FLOOR = 0.22   # below this, an edge says nothing
MAP_EDGES_PER_NODE = 3  # keep each page's strongest few; a dense hairball reads as noise


NEIGHBOURS_PER_PAGE = 3


def similarity_graph(pages, floor=MAP_EDGE_FLOOR, per_node=MAP_EDGES_PER_NODE):
    """Returns (nodes, edges, neighbours), all by TF-IDF cosine.

    Every pair above the floor would be a hairball on a 120-page site, so the
    drawn edges keep only each page's strongest few links. `neighbours` is the
    same data unpruned to a per-page top-N, because "what is this page closest
    to" is the question a reader actually has, and it should not be answerable
    only for the pages that happened to get flagged.

    The cosine loop is the expensive part of a scan, so both come out of one
    pass rather than being recomputed.
    """
    live = [p for p in pages if len(p.get("terms") or ()) >= TOPIC_MIN_TERMS]
    if len(live) < 3:
        return [], [], {}

    vectors = tfidf_vectors(live)
    best = defaultdict(list)
    for i in range(len(live)):
        for j in range(i + 1, len(live)):
            score = cosine(vectors[i], vectors[j])
            if score >= floor:
                best[i].append((score, j))
                best[j].append((score, i))

    edges, neighbours = {}, {}
    for i, candidates in best.items():
        candidates.sort(reverse=True)
        neighbours[i] = candidates[:NEIGHBOURS_PER_PAGE]
        for score, j in candidates[:per_node]:
            edges[frozenset((i, j))] = score
    return (live,
            [(min(p), max(p), s) for p, s in
             sorted(edges.items(), key=lambda kv: kv[1])],
            neighbours)


LAYOUT_SPAN = 1000.0
LAYOUT_GRAVITY = 1.0    # 1.0 puts equilibrium at about the domain radius


def layout_force(node_count, edges, iterations=300):
    """Fruchterman-Reingold spring layout. Deterministic — no RNG.

    Same site scanned twice must draw the same picture, or two runs cannot be
    compared. Initial placement is a golden-angle spiral for that reason.

    Two things this has to get right, both learned by looking at the output:

    - **Gravity is not optional.** Most pages on a real site share vocabulary
      with nothing, so they have no edges and feel only repulsion — which flings
      them to the boundary and draws a ring with everything interesting crushed
      in the middle. A pull toward the centre keeps unconnected pages in frame.
    - **Scale the domain, not the forces.** Working in a 1000-unit square with
      k = sqrt(area/n) puts the equilibrium edge length at k, where repulsion
      k^2/d and attraction d^2/k balance. In normalised 0-1 coordinates the same
      formulas overshoot on every step and the graph never settles.
    """
    if node_count < 1:
        return []

    centre = LAYOUT_SPAN / 2.0
    pos = []
    for i in range(node_count):
        radius = math.sqrt((i + 0.5) / node_count) * centre * 0.9
        angle = i * GOLDEN_ANGLE
        pos.append([centre + radius * math.cos(angle),
                    centre + radius * math.sin(angle)])

    k = math.sqrt((LAYOUT_SPAN * LAYOUT_SPAN) / node_count)
    temp = LAYOUT_SPAN / 8.0
    cooling = temp / (iterations + 1)
    min_dist = k * 0.01

    # Gravity has to balance repulsion, and total repulsion on one node grows
    # with node count: roughly n*k^2/R at radius R. Setting the inward pull to
    # n*k^2/centre^2 per unit of offset puts equilibrium near the domain radius.
    # Since k^2 = span^2/n, the n cancels and this is simply 4*LAYOUT_GRAVITY —
    # derived rather than tuned, which is why it holds at any page count.
    gravity = LAYOUT_GRAVITY * node_count * k * k / (centre * centre)

    for _ in range(iterations):
        disp = [[0.0, 0.0] for _ in range(node_count)]

        for i in range(node_count):
            xi, yi = pos[i]
            for j in range(i + 1, node_count):
                dx, dy = xi - pos[j][0], yi - pos[j][1]
                dist = math.sqrt(dx * dx + dy * dy)
                if dist < min_dist:
                    # Deterministic nudge apart, never a random one.
                    dx, dy = (i - j) or 1, (j - i) or 1
                    dist = math.sqrt(dx * dx + dy * dy)
                force = (k * k) / dist
                ux, uy = dx / dist, dy / dist
                disp[i][0] += ux * force
                disp[i][1] += uy * force
                disp[j][0] -= ux * force
                disp[j][1] -= uy * force

        for a, b, weight in edges:
            dx, dy = pos[a][0] - pos[b][0], pos[a][1] - pos[b][1]
            dist = math.sqrt(dx * dx + dy * dy) or min_dist
            # Similarity scales the spring, so closer really does mean more
            # alike — the one inference the reader may draw from distance.
            force = (dist * dist) / k * weight
            ux, uy = dx / dist, dy / dist
            disp[a][0] -= ux * force
            disp[a][1] -= uy * force
            disp[b][0] += ux * force
            disp[b][1] += uy * force

        for i in range(node_count):
            disp[i][0] += (centre - pos[i][0]) * gravity
            disp[i][1] += (centre - pos[i][1]) * gravity

            dx, dy = disp[i]
            length = math.sqrt(dx * dx + dy * dy)
            if length > 1e-12:
                step = min(length, temp) / length
                pos[i][0] += dx * step
                pos[i][1] += dy * step
        temp -= cooling

    return pos


def jaccard(a, b):
    if not a or not b:
        return 0.0
    inter = len(a & b)
    if not inter:
        return 0.0
    return inter / float(len(a | b))


def is_indexable(page):
    """Would Google index this page as itself?

    Screaming Frog restricts duplicate detection to indexable pages by default,
    and it is right to: a noindexed page, or one canonicalised to a different
    URL, has already been told not to compete. Flagging it as duplicate creates
    work that fixes nothing.
    """
    if page.get("noindex"):
        return False
    canon = (page.get("canonical") or "").strip()
    if canon:
        here = (page.get("final_url") or page.get("url") or "").rstrip("/")
        if canon.rstrip("/") != here:
            return False
    return True


def find_exact_duplicates(pages):
    """Byte-identical body text, grouped. Screaming Frog's 'Exact Duplicates'.

    Free — the hash is already computed during parsing — and worth separating
    from near-duplicates, because identical pages are an unambiguous defect
    while 91%-similar pages need a human to look.
    """
    by_hash = defaultdict(list)
    for p in pages:
        if p.get("text_hash") and p.get("words"):
            by_hash[p["text_hash"]].append(p)
    return [sorted(g, key=lambda p: p["url"])
            for g in by_hash.values() if len(g) > 1]


def find_duplicates(pages, threshold=DUPE_RATIO):
    """Group near-identical pages, after subtracting site-wide boilerplate.

    Without the boilerplate step every page on a template-driven site looks
    ~70% similar to every other and the check is noise. Any phrase appearing on
    more than BOILERPLATE_AT of pages is chrome the parser did not catch.
    """
    live = [p for p in pages if p.get("shingles")]
    if len(live) < 2:
        return [], 0

    boilerplate = set()
    if len(live) >= BOILERPLATE_MIN:
        counts = Counter()
        for p in live:
            counts.update(p["shingles"])
        cutoff = max(3, int(len(live) * BOILERPLATE_AT))
        boilerplate = {s for s, n in counts.items() if n >= cutoff}

    for p in live:
        stripped = p["shingles"] - boilerplate
        # A cluster of identical pages pushes its own content over the
        # boilerplate threshold and erases itself — which is how a set of
        # templated city pages, the exact thing worth catching, comes back
        # clean. When stripping leaves a page with nothing, compare its full
        # text instead: two pages identical after chrome removal are still
        # identical, and a page with no distinctive content is worth flagging
        # either way.
        p["unique_shingles"] = stripped if len(stripped) >= MIN_UNIQUE else p["shingles"]

    # Bucket by length first so we only compare pages that could plausibly match.
    live.sort(key=lambda p: len(p["unique_shingles"]))
    groups, claimed = [], set()

    for i, a in enumerate(live):
        if a["url"] in claimed or len(a["unique_shingles"]) < MIN_UNIQUE:
            continue
        cluster = []
        a_len = len(a["unique_shingles"])
        for b in live[i + 1:]:
            b_len = len(b["unique_shingles"])
            if b_len > a_len * 2:
                break                       # sorted, so nothing further can match
            if b["url"] in claimed:
                continue
            sim = jaccard(a["unique_shingles"], b["unique_shingles"])
            if sim >= threshold:
                cluster.append((b, sim))
        if cluster:
            claimed.add(a["url"])
            for b, _ in cluster:
                claimed.add(b["url"])
            groups.append({
                "primary": a,
                "matches": sorted(cluster, key=lambda t: -t[1]),
            })

    return groups, len(boilerplate)


