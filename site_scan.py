def is_blog(url):
    """Coarse: does this URL look like a blog post or archive page?

    The blog index itself counts — its meta is as templated as the posts'.
    """
    path = urllib.parse.urlparse(url).path.lower()
    if BLOG_DATE_RE.search(path.rstrip("/") + "/"):
        return True
    return any(seg in BLOG_PATH_SEGMENTS for seg in path.split("/") if seg)


def is_banner(url):
    """Does this image look like a banner or hero? Filename is all we have.

    Imperfect on purpose: the alternative is measuring rendered dimensions,
    which needs the browser we deliberately do not run.
    """
    name = urllib.parse.urlparse(url).path.lower()
    return any(h in name for h in BANNER_HINTS)


def content_split(pages):
    """Three buckets, as percentages: duplicate / common / unique.

    Clusters answer "which pages"; this answers "how much", which is the number
    people usually want to track over time. Both are worth having.

    A phrase on nearly every page is chrome ("common"). A phrase on a handful of
    pages but not all is real duplication. Everything else is unique. Siteliner
    reports the same three buckets, so the shape is deliberately familiar.
    """
    live = [p for p in pages if p.get("shingles")]
    if not live:
        return None

    counts = Counter()
    for p in live:
        counts.update(p["shingles"])
    common_at = max(3, int(len(live) * BOILERPLATE_AT)) if len(live) >= BOILERPLATE_MIN \
        else len(live) + 1      # too few pages to call anything chrome

    dup = com = uniq = 0
    for p in live:
        for s in p["shingles"]:
            n = counts[s]
            if n >= common_at:
                com += 1
            elif n > 1:
                dup += 1
            else:
                uniq += 1

    total = dup + com + uniq
    if not total:
        return None
    pct = lambda v: round(v * 100.0 / total, 1)
    return {
        "duplicate_pct": pct(dup), "common_pct": pct(com),
        "unique_pct": pct(uniq), "pages_measured": len(live),
        # Siteliner also separates chrome into a "Common Content" bucket, so
        # duplicate_pct is broadly comparable to its Duplicate Content figure and
        # a benchmark set against that one carries over. The other two do not:
        # this strips nav/header/footer/aside at parse time rather than bucketing
        # them, so common_pct lands near zero and unique_pct is correspondingly
        # inflated against a denominator that still includes chrome.
        "basis": "body text; nav/header/footer/aside removed at parse time",
        "duplicate_pct_comparable_to_siteliner": True,
        "unique_pct_comparable_to_siteliner": False,
    }


def norm_url(href, page_url):
    """Absolute, fragment-free URL. Returns None for non-http schemes."""
    href = html.unescape(href.strip())
    if not href or href.startswith("#"):
        return None
    low = href.lower()
    if low.startswith(("mailto:", "tel:", "javascript:", "data:", "sms:")):
        return None
    try:
        absolute = urllib.parse.urljoin(page_url, href)
    except ValueError:
        return None
    if not absolute.lower().startswith(("http://", "https://")):
        return None
    return urllib.parse.urldefrag(absolute)[0]


def scan_page(url, site_host, opts):
    """Fetch and parse one page. Link/image status checks happen later."""
    r = fetch(url)
    # A throttled page is not one missing row: every link and image on it drops
    # out of the crawl, so a 429 here quietly shrinks coverage and makes the
    # broken-link count differ between runs of the same site.
    attempt = 0
    while r.status in RETRY_STATUS and attempt < MAX_RETRIES:
        time.sleep(retry_after(None, attempt))
        r = fetch(url)
        attempt += 1
    page = {
        "url": url, "final_url": r.final_url, "status": r.status,
        "error": r.error, "redirected": r.redirected,
    }
    if not r.ok or "html" not in (r.ctype or "text/html"):
        page["skipped"] = not r.ok
        return page

    p = parse_page(r.body)
    text = p.text
    words = len(WORD_RE.findall(text))

    links, images = [], []
    for l in p.links:
        target = norm_url(l["href"], r.final_url)
        if target:
            links.append(dict(l, target=target,
                              internal=urllib.parse.urlparse(target).netloc.lower()
                              .replace("www.", "") == site_host))
    for im in p.images:
        target = norm_url(im["src"], r.final_url)
        if target:
            images.append(dict(im, target=target))

    page.update({
        "title": p.title or "",
        "meta_desc": p.meta_desc or "",
        "meta_robots": p.meta_robots,
        "canonical": p.canonical or "",
        "lang": p.lang or "",
        "h1s": p.h1s,
        "words": words,
        "text_hash": hashlib.sha1(text.encode("utf-8", "replace")).hexdigest(),
        "shingles": shingles(text),
        "terms": terms_of(text),
        "links": links,
        "images": images,
        "noindex": "noindex" in p.meta_robots,
    })
    return page


def check_assets(pages, cache, opts, progress=None):
    """Resolve every distinct link and image once, in parallel."""
    link_targets, image_targets = set(), set()
    for pg in pages:
        for l in pg.get("links", []):
            if l["internal"] or opts.external:
                link_targets.add(l["target"])
        for im in pg.get("images", []):
            image_targets.add(im["target"])

    todo = [(u, "link") for u in sorted(link_targets)]
    todo += [(u, "image") for u in sorted(image_targets - link_targets)]
    if not todo:
        return {}

    results, done = {}, [0]
    lock = threading.Lock()

    def one(item):
        url, kind = item
        res = cache.get(url, lambda u: probe(u, timeout=opts.timeout))
        with lock:
            results[url] = res
            done[0] += 1
            if progress and done[0] % 25 == 0:
                progress(done[0], len(todo))
        return res

    with concurrent.futures.ThreadPoolExecutor(max_workers=opts.workers) as ex:
        list(ex.map(one, todo))

    if progress:
        progress(len(todo), len(todo))
    return results


def build_findings(pages, assets, opts):
    """Turn raw page data into the issue lists the report renders."""
    live = [p for p in pages if p.get("status") and p["status"] < 400
            and not p.get("skipped") and "title" in p]

    f = defaultdict(list)

    # -- fetch failures
    for p in pages:
        if p.get("error"):
            f["unreachable"].append({"url": p["url"], "detail": p["error"],
                                     "text": p["error"]})
        elif p.get("status") and p["status"] >= 400:
            f["page_error"].append({"url": p["url"],
                                    "detail": "HTTP %s" % p["status"],
                                    "status": p["status"]})

    # -- titles, descriptions, H1s
    by_title, by_desc = defaultdict(list), defaultdict(list)
    for p in live:
        t, d = p["title"].strip(), p["meta_desc"].strip()
        if not t:
            f["title_missing"].append({"url": p["url"], "detail": ""})
        else:
            by_title[t.lower()].append(p["url"])
            for bucket, test in (("title_long", len(t) > TITLE_MAX),
                                 ("title_short", len(t) < TITLE_MIN)):
                if test:
                    f[bucket].append({
                        "url": p["url"], "detail": "%d chars — %s" % (len(t), t),
                        "value": len(t), "unit": "characters", "text": t})
        if not d:
            f["desc_missing"].append({"url": p["url"], "detail": ""})
        else:
            by_desc[d.lower()].append(p["url"])
            for bucket, test in (("desc_long", len(d) > DESC_MAX),
                                 ("desc_short", len(d) < DESC_MIN)):
                if test:
                    f[bucket].append({
                        "url": p["url"], "detail": "%d chars" % len(d),
                        "value": len(d), "unit": "characters", "text": d})

        if not p["h1s"]:
            f["h1_missing"].append({"url": p["url"], "detail": ""})
        elif len(p["h1s"]) > 1:
            f["h1_multiple"].append({
                "url": p["url"],
                "detail": "%d H1s — %s" % (len(p["h1s"]), " | ".join(p["h1s"][:3])),
                "value": len(p["h1s"]), "unit": "H1 tags",
                "text": " | ".join(p["h1s"][:5]),
            })
        if p["words"] < THIN_WORDS and not p.get("noindex"):
            f["thin"].append({"url": p["url"], "detail": "%d words" % p["words"],
                              "value": p["words"], "unit": "words"})

    for t, urls in by_title.items():
        if len(urls) > 1:
            f["title_duplicate"].append({
                "url": urls[0], "detail": "%d pages share this title" % len(urls),
                "group": urls[1:], "value": len(urls), "unit": "pages", "text": t,
            })
    for d, urls in by_desc.items():
        if len(urls) > 1:
            f["desc_duplicate"].append({
                "url": urls[0], "detail": "%d pages share this description" % len(urls),
                "group": urls[1:], "value": len(urls), "unit": "pages", "text": d,
            })

    # -- images
    seen_img = set()
    alt_missing, alt_empty = defaultdict(list), defaultdict(list)
    for p in live:
        for im in p["images"]:
            # Keyed by image, not by occurrence. One logo in the header is one
            # fix, not one fix per page — counting occurrences turns a 3-item
            # job into a 399-item wall nobody reads.
            if im["alt_missing"]:
                alt_missing[im["target"]].append(p["url"])
            elif im["alt_empty"] and not im["decorative"]:
                alt_empty[im["target"]].append(p["url"])

            if im["target"] in seen_img:
                continue
            seen_img.add(im["target"])
            res = assets.get(im["target"])
            if not res:
                continue
            if res.error or (res.status and res.status >= 400):
                f["image_broken"].append({
                    "url": im["target"],
                    "detail": "%s — first seen on %s" % (
                        res.error or "HTTP %s" % res.status, p["url"]),
                })
            elif res.length and res.length > IMAGE_KB_BAD * 1024:
                f["image_huge"].append({
                    "url": im["target"],
                    "detail": "%.1f MB — first seen on %s" % (
                        res.length / 1048576.0, p["url"]),
                    "kb": res.length // 1024,
                    "value": res.length // 1024, "unit": "KB",
                    "group": [p["url"]],
                    "sort": -res.length,
                })
            elif res.length:
                banner = is_banner(im["target"])
                budget = opts.banner_kb if banner else opts.image_kb
                if res.length > budget * 1024:
                    f["image_heavy"].append({
                        "url": im["target"],
                        "detail": "%d KB%s — first seen on %s" % (
                            res.length // 1024,
                            " (banner, budget %dKB)" % budget if banner else "",
                            p["url"]),
                        "kb": res.length // 1024,
                        "banner": banner,
                        "value": res.length // 1024, "unit": "KB",
                        "text": "banner" if banner else "",
                        "group": [p["url"]],
                        "sort": -res.length,
                    })

    for bucket, key in ((alt_missing, "alt_missing"), (alt_empty, "alt_empty")):
        for src, on_pages in bucket.items():
            f[key].append({
                "url": src,
                "detail": "on %d page%s (e.g. %s)" % (
                    len(on_pages), "" if len(on_pages) == 1 else "s", on_pages[0]),
                "group": on_pages,
                "value": len(on_pages), "unit": "pages",
                "sort": -len(on_pages),
            })
        f[key].sort(key=lambda r: r["sort"])

    for key in ("image_huge", "image_heavy"):
        f[key].sort(key=lambda r: r.get("sort", 0))

    # -- links
    broken = defaultdict(list)
    unverified = defaultdict(list)
    redirects = defaultdict(list)
    internal_targets = set()
    for p in live:
        for l in p["links"]:
            if not l["internal"] and not opts.external:
                continue
            res = assets.get(l["target"])
            if not res:
                continue
            if l["internal"]:
                internal_targets.add(l["target"])
            if res.throttled:
                # Still rate-limited after every retry. Its real status is
                # unknown, and "unknown" must never be published as "broken".
                unverified[l["target"]].append((p["url"], l["anchor"], res))
            elif res.error or (res.status and res.status >= 400):
                broken[l["target"]].append((p["url"], l["anchor"], res))
            elif l["internal"] and res.redirected and res.status and res.status < 400:
                redirects[l["target"]].append((p["url"], res.final_url))

    for target, hits in broken.items():
        res = hits[0][2]
        internal = target in internal_targets
        f["link_broken"].append({
            "url": target,
            # The two want different fixes: an internal 4xx gets a redirect, an
            # external one gets the link removed or repointed.
            "detail": "%s%s — linked from %d page%s (e.g. %s)" % (
                "internal, " if internal else "",
                res.error or "HTTP %s" % res.status,
                len(hits), "" if len(hits) == 1 else "s", hits[0][0]),
            "group": [h[0] for h in hits],
            "internal": internal,
            "status": res.status or (res.error or "")[:40],
            "value": len(hits), "unit": "pages linking",
            "text": "internal" if internal else "external",
            "sort": (0 if internal else 1, -len(hits)),
        })
    f["link_broken"].sort(key=lambda r: r["sort"])

    for target, hits in unverified.items():
        res = hits[0][2]
        f["link_unverified"].append({
            "url": target,
            "detail": "rate-limited (HTTP %s) after %d attempts — status unknown, "
                      "linked from %d page%s" % (
                          res.status, MAX_RETRIES + 1, len(hits),
                          "" if len(hits) == 1 else "s"),
            "group": [h[0] for h in hits],
            "internal": target in internal_targets,
            "status": res.status,
            "value": len(hits), "unit": "pages linking",
            "text": "status unknown — not confirmed broken",
            "sort": -len(hits),
        })
    f["link_unverified"].sort(key=lambda r: r["sort"])

    for target, hits in redirects.items():
        f["link_redirect"].append({
            "url": target,
            "detail": "-> %s — linked from %d page%s" % (
                hits[0][1], len(hits), "" if len(hits) == 1 else "s"),
            "group": [h[0] for h in hits],
            "sort": -len(hits),
        })
    f["link_redirect"].sort(key=lambda r: r["sort"])

    # Label the page-level meta findings by page type. Images and links are
    # deliberately NOT segmented: a broken link or a 2 MB image is a defect
    # wherever it lives, and tagging the blog-category 404s as "blog" would bury
    # the largest finding on a blog-heavy site.
    for key in BLOG_SEGMENTED:
        for r in f.get(key) or []:
            r["blog"] = is_blog(r["url"])
        if getattr(opts, "exclude_blog", False):
            f[key] = [r for r in f.get(key) or [] if not r["blog"]]

    # -- duplicate content, on indexable pages only (Screaming Frog's default)
    indexable = [p for p in live if is_indexable(p)]

    for g in find_exact_duplicates(indexable):
        f["content_exact"].append({
            "url": g[0]["url"],
            "detail": "identical to %d other page%s: %s" % (
                len(g) - 1, "" if len(g) == 2 else "s",
                ", ".join(p["url"] for p in g[1:4])),
            "group": [p["url"] for p in g[1:]],
            "value": len(g), "unit": "identical pages",
        })

    exact_seen = {u for r in f["content_exact"]
                  for u in [r["url"]] + r.get("group", [])}
    groups, boiler = find_duplicates(indexable, opts.dupe_ratio)
    for g in groups:
        # Already reported as byte-identical; don't say it twice.
        if g["primary"]["url"] in exact_seen:
            continue
        f["content_duplicate"].append({
            "url": g["primary"]["url"],
            "detail": "%d near-identical page%s: %s" % (
                len(g["matches"]), "" if len(g["matches"]) == 1 else "s",
                ", ".join("%s (%d%%)" % (b["url"], round(s * 100))
                          for b, s in g["matches"][:3])),
            "group": [b["url"] for b, _ in g["matches"]],
            "value": round(max(s for _, s in g["matches"]) * 100),
            "unit": "% similar",
        })

    # -- same topic, different words. Pairs already reported as duplicates would
    # only be said twice, so skip them.
    dupe_seen = {u for key in ("content_exact", "content_duplicate")
                 for r in f.get(key) or [] for u in [r["url"]] + r.get("group", [])}
    for members, low, high in topic_clusters(
            indexable, getattr(opts, "topic_ratio", TOPIC_RATIO),
            getattr(opts, "include_blog_topics", False)):
        if all(u in dupe_seen for u in members):
            continue
        head, rest = members[0], members[1:]
        f["content_topic"].append({
            "url": head,
            "detail": "%d pages share %d-%d%% of their vocabulary: %s" % (
                len(members), round(low * 100), round(high * 100),
                ", ".join(rest[:3]) + (", ..." if len(rest) > 3 else "")),
            "group": rest,
            "value": round(high * 100), "unit": "% term overlap",
            "text": "%d pages" % len(members),
        })

    return f, live, boiler


